/**
 * Generates a local .env with RANDOM secrets (never committed).
 *   npm run setup:env                 -> create .env if missing
 *   npm run setup:env -- --reset-admin -> new admin password (printed once)
 * The admin password is never stored in plain text; only a bcrypt hash.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { resolve } from "node:path";
import bcrypt from "bcryptjs";

const envPath = resolve(process.cwd(), ".env");
const resetAdmin = process.argv.includes("--reset-admin");

function parse(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)="?(.*?)"?$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

const existing = existsSync(envPath) ? parse(readFileSync(envPath, "utf8")) : {};
const hasReal =
  existing.SESSION_SECRET && existing.ADMIN_PASSWORD_HASH && existing.DATABASE_URL?.includes("54329");

if (hasReal && !resetAdmin) {
  console.log(".env already configured. Use --reset-admin to issue a new admin password.");
  process.exit(0);
}

const dbPassword = hasReal ? new URL(existing.DATABASE_URL).password : randomBytes(18).toString("hex");
const sessionSecret = hasReal ? existing.SESSION_SECRET : randomBytes(48).toString("hex");
const adminPassword = randomBytes(9).toString("base64url");
const hash = bcrypt.hashSync(adminPassword, 12);
// bcrypt hashes contain "$": escape for dotenv-expand safety
const escapedHash = hash.replace(/\$/g, "\\$");

const body = [
  "# Generated by scripts/setup-env.ts — local only, never commit.",
  `DATABASE_URL="postgresql://up_demo:${dbPassword}@localhost:54329/unitedpapers?schema=public"`,
  `SESSION_SECRET="${sessionSecret}"`,
  'ADMIN_EMAIL="owner@unitedpapers.demo"',
  `ADMIN_PASSWORD_HASH="${escapedHash}"`,
  'NEXT_PUBLIC_DEMO_BANNER="true"',
  "",
].join("\n");

writeFileSync(envPath, body, { encoding: "utf8" });
console.log("\n.env written.");
console.log("Admin login (shown ONCE, not stored in plain text):");
console.log("  email:    owner@unitedpapers.demo");
console.log(`  password: ${adminPassword}\n`);

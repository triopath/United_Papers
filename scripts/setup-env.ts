/**
 * Generates a local .env with RANDOM secrets (never committed).
 *   npm run setup:env      -> create .env if missing
 * Admin users live in the database, not here: after migrating, run
 *   npm run admin:create -- <email> <password>
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { resolve } from "node:path";

const envPath = resolve(process.cwd(), ".env");

function parse(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)="?(.*?)"?$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

const existing = existsSync(envPath) ? parse(readFileSync(envPath, "utf8")) : {};
if (existing.SESSION_SECRET && existing.DATABASE_URL?.includes("54329")) {
  console.log(".env already configured.");
  process.exit(0);
}

const body = [
  "# Generated by scripts/setup-env.ts — local only, never commit.",
  `DATABASE_URL="postgresql://up_demo:${randomBytes(18).toString("hex")}@localhost:54329/unitedpapers?schema=public"`,
  `SESSION_SECRET="${existing.SESSION_SECRET ?? randomBytes(48).toString("hex")}"`,
  'NEXT_PUBLIC_DEMO_BANNER="true"',
  "",
].join("\n");

writeFileSync(envPath, body, { encoding: "utf8" });
console.log(".env written. Next: npm run db:start, npm run db:migrate, npm run db:seed, then npm run admin:create -- <email> <password>");
